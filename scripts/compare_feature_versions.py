"""Compare versions of versioned features via the feature store.
Generates VERSION_COMPARISON.md as output.
"""

import sys
import os
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import numpy as np
from feature_store import store


def compute_comparison(feature_name):
    """Load all versions from the store and produce a comparison."""
    versions_df = store.list_versions(feature_name)
    if len(versions_df) < 2:
        print(f"WARNING: {feature_name} has only {len(versions_df)} version(s), skipping comparison.")
        return None

    versions = sorted(versions_df['version'].tolist())

    # Load all versions
    data = {}
    for v in versions:
        df = store.get_version(feature_name, v)
        if df is not None:
            data[v] = df.set_index('customer_id')[feature_name]

    if len(data) < 2:
        return None

    # Align on customer_id
    common_ids = data[versions[0]].index.intersection(data[versions[1]].index)

    # For this feature set, all versions cover the same 1500 customers, so length = 1500
    total = len(common_ids)

    results = {}
    comparisons = [(versions[i], versions[j]) for i in range(len(versions))
                   for j in range(i+1, len(versions))]

    for v_a, v_b in comparisons:
        a = data[v_a].loc[common_ids]
        b = data[v_b].loc[common_ids]

        changed = (a != b).sum()
        diff = (b - a).dropna()

        result = {
            'total': total,
            'changed': changed,
            'pct_changed': 100.0 * changed / total if total > 0 else 0.0,
            'diff_stats': {
                'mean': diff.mean(),
                'std': diff.std(),
                'min': diff.min(),
                'max': diff.max(),
            },
            'a_stats': {
                'mean': a.mean(),
                'std': a.std(),
                'min': a.min(),
                'max': a.max(),
            },
            'b_stats': {
                'mean': b.mean(),
                'std': b.std(),
                'min': b.min(),
                'max': b.max(),
            },
        }
        results[f'v{v_a}_vs_v{v_b}'] = result

    return results


def get_drift_assessment(feature_name, comparison):
    """Return a qualitative assessment of the version change impact."""
    comp = list(comparison.values())[0]  # only one pair for now
    pct = comp['pct_changed']
    diff_mean = abs(comp['diff_stats']['mean'])

    if pct < 1:
        return ("**Negligible impact.** Fewer than 1% of customers are affected. "
                "A model consuming this feature would rarely see a difference.")
    elif pct < 5:
        return ("**Minor impact.** Under 5% of customers see changed values. "
                "The model would notice on the affected subset, but overall distribution shift is small.")
    elif pct < 20:
        return ("**Moderate impact.** Between 5–20% of customers are affected. "
                "The model would register this shift, especially for the changed customers. "
                "Retraining on the new version is advisable.")
    else:
        return ("**Significant impact.** Over 20% of customers see changed values. "
                "A model consuming this feature would definitely notice "
                "— retraining is strongly recommended before deploying this version.")


def main():
    versioned_features = ['recent_net_spend_window', 'lifetime_return_rate']

    print("Generating version comparison...\n")

    sections = []

    sections.append("# VERSION_COMPARISON.md")
    sections.append("")
    sections.append("> Auto-generated by scripts/compare_feature_versions.py")
    sections.append("")

    for feat_name in versioned_features:
        results = compute_comparison(feat_name)
        if results is None:
            continue

        sections.append(f"## {feat_name}")
        sections.append("")

        ver_list = store.list_versions(feat_name)
        for _, row in ver_list.iterrows():
            sections.append(f"- **v{row['version']}**: parameters = {row['parameters']}, "
                          f"rationale: {row['business_rationale']}")
        sections.append("")

        for pair_key, comp in results.items():
            sections.append(f"### Comparison: {pair_key}")
            sections.append("")
            sections.append(f"- **Total customers compared:** {comp['total']}")
            sections.append(f"- **Customers with changed values:** {comp['changed']} "
                          f"({comp['pct_changed']:.2f}%)")
            sections.append("")
            sections.append("#### Distribution: v1 -> v2 difference (per customer)")
            sections.append(f"- Mean diff: {comp['diff_stats']['mean']:.6f}")
            sections.append(f"- Std diff:  {comp['diff_stats']['std']:.6f}")
            sections.append(f"- Min diff:  {comp['diff_stats']['min']:.6f}")
            sections.append(f"- Max diff:  {comp['diff_stats']['max']:.6f}")
            sections.append("")
            sections.append("#### v1 summary stats")
            sections.append(f"- Mean: {comp['a_stats']['mean']:.6f}, "
                          f"Std: {comp['a_stats']['std']:.6f}")
            sections.append(f"- Range: [{comp['a_stats']['min']:.6f}, {comp['a_stats']['max']:.6f}]")
            sections.append("")
            sections.append("#### v2 summary stats")
            sections.append(f"- Mean: {comp['b_stats']['mean']:.6f}, "
                          f"Std: {comp['b_stats']['std']:.6f}")
            sections.append(f"- Range: [{comp['b_stats']['min']:.6f}, {comp['b_stats']['max']:.6f}]")
            sections.append("")
            sections.append("### Interpretation")
            sections.append("")
            sections.append(get_drift_assessment(feat_name, results))
            sections.append("")

    # Write VERSION_COMPARISON.md
    output_path = os.path.join(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
        'VERSION_COMPARISON.md'
    )
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(sections))

    print(f"Wrote {output_path}")
    for line in sections:
        print(line)


if __name__ == '__main__':
    main()